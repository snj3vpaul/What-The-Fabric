// Defaults so older entries need not spell them out.
//   stretch (0–5): woven cloth barely stretches; knits with elastane stretch a lot.
//   wick (0–5):    how well the cloth moves sweat to its outer face to evaporate, even if the
//                  fibre itself absorbs almost nothing (performance polyester).
const STRETCHY_WOVENS = { georgette: 1, crepe: 1, net: 1, chiffon: 1 };
for (const f of FABRICS) {
  f.scales.stretch ??= STRETCHY_WOVENS[f.id] ?? 0;
  f.thermal.wick ??= 0;
}

